import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { censusManifestFileSchema, type CensusManifestFile } from "../src/domain/coverage-targets";

// Helper to write and validate census
function saveCensus(filename: string, census: CensusManifestFile) {
  const validated = censusManifestFileSchema.parse(census);
  const outPath = resolve(process.cwd(), `catalog/census/${filename}`);
  writeFileSync(outPath, JSON.stringify(validated, null, 2), "utf-8");
  console.log(`Saved and validated census: ${filename} with ${validated.entries.length} models (${validated.supplyExceptions.length} exceptions)`);
}

